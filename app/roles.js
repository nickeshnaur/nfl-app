/* ============================================================================
   Text-role tagger. Most text roles are locked by selector in app/css/roles.css. Some elements draw more than one
   kind of content from the same markup: a table cell is a tricode in one row and a yardage in the next, a chip is a
   team in one place and a filter in another. For those (App.ROLE_MIXED: selector → the roles it may be tagged with,
   from app/roles-data.js, generated by _build/roles.mjs) this reads the text and adds r-tricode, r-record… so
   roles.css can give each its face. Big Display numbers (stat tiles) are not offered stat-number, so they stay Display.
   It runs on every change to the page, so new data is always tagged the same way.
   ========================================================================== */
(function () {
'use strict';
const App = window.App;
let ABBR, NAMES, PLAYERS;
const prep = () => {
  if (ABBR && PLAYERS.size) return true; // players load after teams: keep building until they are in
  const T = (App.data && App.data.D && App.data.D.teams) || []; if (!T.length) return false;
  ABBR = new Set(T.map(t => t.abbr)); NAMES = new Set(T.flatMap(t => [t.name, t.full, t.nick].filter(Boolean).map(s => s.toLowerCase())));
  PLAYERS = new Set(); try { Object.values(App.data.D.players || {}).forEach(p => p && (p.n || p.name) && PLAYERS.add(String(p.n || p.name).toLowerCase())); } catch (e) {}
  return true;
};
/** the same rules as the crawl (_build/audit.mjs), for the roles that have a pick */
/* a one- or two-digit number next to a tricode is a score (the crawl's rule) */
const near = el => { const p = el.parentElement; if (!p) return false; if ([...p.childNodes].some(c => c.nodeType === 3 && ABBR.has(c.nodeValue.trim()))) return true; return [...p.children].concat(p.parentElement ? [...p.parentElement.children] : []).some(s => s !== el && ABBR.has((s.textContent || '').trim())); };
function role(t, el) {
  if (el && el.closest('.btn, .chip, .seg button, .tm-sw, .pill-tabs button, .phead-title, .r-sans')) return null; // controls and page titles have their own role; .r-sans rows keep team names in Sans (you-follow, approved 2026-11-07)
  if (ABBR.has(t)) return 'tricode';
  if (NAMES.has(t.toLowerCase())) return 'team-name';
  if (/^(Q[1-4]|OT|Final|Final\/OT|Halftime|(1st|2nd|3rd|4th|OT) \d{1,2}:\d{2}|\d{1,2}:\d{2}|End of \w+)$/i.test(t)) return 'clock-status';
  if (/^(1st|2nd|3rd|4th) & (\d+|Goal)( at .+)?$/i.test(t)) return 'down-distance';
  if (/^\d{1,2}-\d{1,2}(-\d)?$/.test(t)) return 'record';
  if (/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun)[a-z]*,? (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* \d{1,2}/.test(t)) return 'date';
  if (/^((Mon|Tue|Wed|Thu|Fri|Sat|Sun)[a-z]* )?\d{1,2}:\d{2} ?[AP]M( [A-Z]{2,4})?$/.test(t)) return 'date'; // kickoff time: the Date card covers it
  if (/^\d{1,2}$/.test(t) && el && !el.closest('td, th') && near(el)) return 'score'; // in a table, a number is a stat
  if (PLAYERS.has(t.toLowerCase())) return 'player-name';
  if (/^[+-]?\d[\d,]*(\.\d+)?%?$/.test(t)) return 'stat-number';
  return null;
}
const R = ['tricode', 'team-name', 'score', 'player-name', 'clock-status', 'down-distance', 'record', 'date', 'stat-number'].map(r => 'r-' + r);
function tag(root) {
  const M = App.ROLE_MIXED; if (!M || !prep()) return;
  // one decision per element: an element matched by several selectors may take any role any of them allows
  const allow = new Map();
  for (const [sel, ok] of Object.entries(M)) { let q; try { q = root.querySelectorAll(sel); } catch (e) { continue; }
    q.forEach(el => { const a = allow.get(el) || new Set(); ok.forEach(r => a.add(r)); allow.set(el, a); }); }
  allow.forEach((ok, el) => {
    if (el.hasAttribute('data-r')) return; // a wrapper this made: its role is already decided
    const texts = [...el.childNodes].filter(c => c.nodeType === 3 && c.nodeValue.trim());
    const own = texts.map(c => c.nodeValue).join('').replace(/\s+/g, ' ').trim();
    const r0 = own ? role(own, el) : null, r = ok.has(r0) ? r0 : null, want = r && 'r-' + r;
    if ([...el.children].some(c => (c.textContent || '').trim())) {
      // a container (a table cell with a logo, a row title with a pill): wrap only its own text, so nothing leaks
      if (want && texts.length === 1) { const sp = document.createElement('span'); sp.className = want; sp.dataset.r = ''; texts[0].replaceWith(sp); sp.appendChild(texts[0]); }
      return;
    }
    if (want && el.classList.contains(want)) return;
    el.classList.remove(...R); if (want) el.classList.add(want);
  });
}
let t = 0;
const run = () => { t = 0; tag(document.body); };
new MutationObserver(() => { if (!t) t = requestAnimationFrame(run); }).observe(document.documentElement, { childList: true, subtree: true, characterData: true });
App.roleTag = tag; App.roleOf = (t, el) => prep() && role(t, el);
})();
